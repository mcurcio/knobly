"""Generate each binding's fixed API lists from spec/schema/ (spec/codegen.md).

    python3 tools/gen-api.py ts       -> ts/src/gen/api/{codes,kinds,limits}.ts
    python3 tools/gen-api.py py       -> py/src/villanelle/_api/{__init__,codes,kinds,limits}.py
    python3 tools/gen-api.py --check  -> validates the schema and generates both targets into a temp dir

tools/gen.sh runs it after the parser, so every TypeScript package script and py/tests/conftest.py
regenerate the lists. The output is never committed (owner, 2026-10-23: "Don't commit the generated
code, just the source"). Python 3.9+ standard library only (macOS ships 3.9).

What comes from where:
  codes   spec/schema/diagnostics.json "codes": the code constant per code (name in the binding's
          casing) and the message table; "{<limit name>}" in a message is filled from that limit.
  kinds   spec/schema/api.json "kinds": every list becomes a union of string literals (TypeScript) and a
          StrEnum (Python), the same spelling for every list (milestone 2, round 13 root cause 3). The
          token kinds are read from grammar/Villanelle.g4 (its lexer rule names, fragments aside, in
          declaration order), their one home.
  limits  spec/schema/api.json "limits", "reserved names" and "patterns": each one whose binding
          spelling is an UPPER_SNAKE_CASE name (Number.MAX_SAFE_INTEGER, ProgramCode and
          check_program_code are the language's or hand-written, so they are skipped).

Names follow spec/binding-guide.md rule 1: a spec name is lowercase words (spaces or hyphens); a
binding changes only the casing. Where diagnostics.json also spells a code's binding name, the
spelling must equal the casing rule's result, or generation fails.

--check also validates what the generator does not emit but the public-name checks read: every
concept's variants (spec/schema/api.json "$comment"), that no member carries a deferral marker, and
that every error group's parent exists.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import tempfile
import textwrap
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
API = REPO / "spec" / "schema" / "api.json"
DIAGNOSTICS = REPO / "spec" / "schema" / "diagnostics.json"
GRAMMAR = REPO / "grammar" / "Villanelle.g4"
OUT = {"ts": REPO / "ts" / "src" / "gen" / "api", "py": REPO / "py" / "src" / "villanelle" / "_api"}

HEADER = "Generated by tools/gen-api.py from spec/schema/; do not edit. Never committed (owner, 2026-10-23)."
UPPER_SNAKE = re.compile(r"[A-Z][A-Z0-9_]*")
PLACEHOLDER = re.compile(r"\{([a-z][a-z -]*)\}")


class SchemaError(Exception):
    pass


# --- casing (binding guide rule 1) ---------------------------------------------------------------------------


def words(name: str) -> list[str]:
    parts = re.split(r"[ -]+", name.strip())
    if not parts or not all(re.fullmatch(r"[a-z0-9]+", p) for p in parts):
        raise SchemaError(f"not a spec name (lowercase words): {name!r}")
    return parts


def pascal(name: str) -> str:
    return "".join(w[0].upper() + w[1:] for w in words(name))


def upper_snake(name: str) -> str:
    return "_".join(w.upper() for w in words(name))


def spelled(text: str) -> str | None:
    """The leading identifier of a binding spelling ("RESERVED (written/bind.ts)" -> "RESERVED")."""
    m = re.match(r"[A-Za-z_][A-Za-z0-9_.]*", text)
    return m.group() if m else None


# --- the model both targets render ---------------------------------------------------------------------------


class Code:
    def __init__(self, raw: dict[str, object]) -> None:
        self.code = str(raw["code"])
        self.name = str(raw["name"])
        self.message = str(raw["message"])
        self.meaning = str(raw.get("meaning") or "")
        if not re.fullmatch(r"E[0-9]{4}", self.code):
            raise SchemaError(f"bad code {self.code!r}")
        for lang, rule in (("ts", pascal), ("py", upper_snake)):
            given = raw.get(lang)
            if given is not None and given != rule(self.name):
                raise SchemaError(f"{self.code}: diagnostics.json spells {lang} {given!r}, the casing rule gives {rule(self.name)!r}")


class Kind:
    """One closed list. ``member`` gives each value's member name in a binding's constant casing."""

    def __init__(self, name: str, values: list[str], *, words_only: bool = True) -> None:
        self.name = name
        if not values or len(set(values)) != len(values):
            raise SchemaError(f"kind list {name!r}: values must be a non-empty list without repeats")
        self.values = values
        self.words_only = words_only
        for v in self.values:
            if words_only:
                words(v)
            elif not UPPER_SNAKE.fullmatch(v):
                raise SchemaError(f"kind list {name!r}: {v!r} is not a grammar token name")

    def member_ts(self, value: str) -> str:
        return pascal(value) if self.words_only else value

    def member_py(self, value: str) -> str:
        return upper_snake(value) if self.words_only else value


def grammar_tokens() -> list[str]:
    """The lexer rule names of grammar/Villanelle.g4 in declaration order, fragments aside: the token kinds."""
    text = GRAMMAR.read_text(encoding="utf-8")
    names: list[str] = []
    for line in text.splitlines():
        code = re.sub(r"'(?:\\.|[^'\\])*'", "''", line)  # literals may hold ':' or ';'
        code = code.split("//", 1)[0]
        if code.lstrip().startswith("fragment"):
            continue
        for m in re.finditer(r"(?:^|;)\s*([A-Z][A-Z0-9_]*)\s*:", code):
            names.append(m.group(1))
    if not names:
        raise SchemaError(f"no lexer rules found in {GRAMMAR}")
    return names


def check_concepts(api: dict[str, object], kinds: dict[str, Kind]) -> None:
    """The union and variant structure the public-name checks read (api.json "$comment"), and no deferral marker."""
    concepts = api["concepts"]
    assert isinstance(concepts, list)
    by_name: dict[str, dict[str, object]] = {}
    for c in concepts:
        name = str(c["name"])
        words(name)
        if name in by_name:
            raise SchemaError(f"concept {name!r} listed twice")
        by_name[name] = c
        for m in c.get("members", []):
            words(str(m["name"]))
            if "later" in m:
                raise SchemaError(f"{name}: member {m['name']!r} is deferred ('later'); every member is present in every binding")
    for name, c in by_name.items():
        for ref in ("variant of", "extends"):
            if ref in c and c[ref] not in by_name:
                raise SchemaError(f"{name}: {ref} {c[ref]!r} is no concept")
        if "variant of" in c:
            union = by_name[str(c["variant of"])]
            if name not in union.get("variants", []):  # type: ignore[operator]
                raise SchemaError(f"{name}: its union {c['variant of']!r} does not list it in 'variants'")
        if "variants" not in c:
            continue
        lst = kinds.get(str(c.get("kind list")))
        if lst is None:
            raise SchemaError(f"{name}: 'kind list' {c.get('kind list')!r} is no kind list")
        want = [v for v in lst.values if v not in c.get("except", [])]  # type: ignore[operator]
        got = []
        for v in c["variants"]:  # type: ignore[attr-defined]
            variant = by_name.get(v)
            if variant is None or variant.get("variant of") != name:
                raise SchemaError(f"{name}: variant {v!r} is no concept naming it in 'variant of'")
            got.append(variant.get("kind"))
        if sorted(map(str, got)) != sorted(want):
            raise SchemaError(f"{name}: its variants' kinds {got} are not the {lst.name} list {want}")
    raw_kinds = api["kinds"]
    assert isinstance(raw_kinds, dict)
    for lname, raw in raw_kinds.items():
        for value, concept in raw.get("variants", {}).items():
            if concept not in by_name or by_name[concept].get("kind") != value:
                raise SchemaError(f"kind list {lname!r}: {value!r} maps to {concept!r}, which is no concept of that kind")
        for concept in raw.get("tag of", []):
            if concept not in by_name:
                raise SchemaError(f"kind list {lname!r}: tag of {concept!r}, which is no concept")
    groups = api["error groups"]
    assert isinstance(groups, list)
    names = {g["name"] for g in groups}
    for g in groups:
        if "parent" in g and g["parent"] not in names:
            raise SchemaError(f"error group {g['name']!r}: parent {g['parent']!r} is no error group")


class Constant:
    """One limit, reserved-name set or pattern, with each binding's name (None: not generated there)."""

    def __init__(self, name: str, value: object, ts: str | None, py: str | None, means: str) -> None:
        self.name, self.value, self.means = name, value, means
        self.ts = ts if ts and UPPER_SNAKE.fullmatch(ts) else None
        self.py = py if py and UPPER_SNAKE.fullmatch(py) else None


class Model:
    def __init__(self, api: dict[str, object], diagnostics: dict[str, object]) -> None:
        raw_codes = diagnostics["codes"]
        assert isinstance(raw_codes, list)
        self.codes = [Code(c) for c in raw_codes]
        seen: set[str] = set()
        for c in self.codes:
            if c.code in seen:
                raise SchemaError(f"code {c.code} listed twice")
            seen.add(c.code)
        retired = set(map(str, diagnostics.get("retired", [])))  # type: ignore[call-overload]
        if retired & seen:
            raise SchemaError(f"retired codes still listed: {sorted(retired & seen)}")

        kinds = api["kinds"]
        assert isinstance(kinds, dict)
        self.kinds = []
        for name, raw in kinds.items():
            if "values" in raw:
                self.kinds.append(Kind(name, [str(v) for v in raw["values"]]))
            elif str(raw.get("values from", "")).startswith("grammar/"):
                self.kinds.append(Kind(name, grammar_tokens(), words_only=False))
            else:
                raise SchemaError(f"kind list {name!r}: neither 'values' nor 'values from' the grammar")
        check_concepts(api, {k.name: k for k in self.kinds})

        self.limits: list[Constant] = []
        for raw in api["limits"]:  # type: ignore[attr-defined]
            if not isinstance(raw["value"], int):
                raise SchemaError(f"limit {raw['name']!r}: value must be an integer")
            self.limits.append(Constant(raw["name"], raw["value"], spelled(raw["ts"]), spelled(raw["py"]), raw["means"]))
        reserved = api["reserved names"]
        assert isinstance(reserved, dict)
        self.reserved = Constant(
            "reserved names", list(reserved["words"]), spelled(reserved["ts"]), spelled(reserved["py"]),
            "words no extension may take as its directive name; " + str(reserved.get("also", "")),
        )
        self.patterns: list[Constant] = []
        for name, raw in api["patterns"].items():  # type: ignore[attr-defined]
            regex = raw["regex"]
            if not (regex.startswith("^") and regex.endswith("$")):
                raise SchemaError(f"pattern {name!r}: regex must be anchored with ^ and $")
            re.compile(regex)
            self.patterns.append(Constant(name, regex, spelled(raw["ts"]), spelled(raw["py"]), raw.get("applies to") or raw.get("means", "")))

        self.limit_names = {c.name: c for c in self.limits}
        for c in self.codes:
            for ph in PLACEHOLDER.findall(c.message):
                if ph not in self.limit_names:
                    raise SchemaError(f"{c.code}: message names {{{ph}}}, which is no limit in api.json")


def read_schema() -> tuple[dict[str, object], dict[str, object]]:
    with API.open(encoding="utf-8") as f:
        api = json.load(f)
    with DIAGNOSTICS.open(encoding="utf-8") as f:
        diagnostics = json.load(f)
    return api, diagnostics


def load_model() -> Model:
    return Model(*read_schema())


def planted(api: dict[str, object], diagnostics: dict[str, object]) -> None:
    """Each check of the schema still bites: a broken copy must be refused (as tools/planted/ does for the grammar)."""
    def concept(a: dict[str, object], name: str) -> dict[str, object]:
        return next(c for c in a["concepts"] if c["name"] == name)  # type: ignore[attr-defined]

    def deferred(a: dict[str, object]) -> None:
        concept(a, "place")["members"][0]["later"] = {"py": "a later milestone"}  # type: ignore[index]

    def variant_missing(a: dict[str, object]) -> None:
        concept(a, "variable")["variants"].remove("override variable")  # type: ignore[attr-defined]

    def wrong_kind(a: dict[str, object]) -> None:
        concept(a, "set line")["kind"] = "use"

    def bad_parent(a: dict[str, object]) -> None:
        a["error groups"][0]["parent"] = "no such group"  # type: ignore[index]

    for name, plant in (("deferred member", deferred), ("variant missing", variant_missing), ("wrong kind", wrong_kind), ("bad parent", bad_parent)):
        broken = json.loads(json.dumps(api))
        plant(broken)
        try:
            Model(broken, diagnostics)
        except SchemaError:
            continue
        raise SchemaError(f"planted {name}: not caught")


# --- TypeScript ----------------------------------------------------------------------------------------------


def ts_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def ts_doc(text: str, indent: str = "") -> list[str]:
    text = text.replace("*/", "*\\/").strip()
    if not text:
        return []
    lines = textwrap.wrap(text, 114 - len(indent))
    if len(lines) == 1:
        return [f"{indent}/** {lines[0]} */"]
    return [f"{indent}/**", *(f"{indent} * {line}" for line in lines), f"{indent} */"]


def ts_message(model: Model, message: str) -> tuple[str, set[str]]:
    used: set[str] = set()
    if not PLACEHOLDER.search(message):
        return ts_str(message), used
    out = []
    pos = 0
    for m in PLACEHOLDER.finditer(message):
        out.append(message[pos : m.start()].replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${"))
        name = model.limit_names[m.group(1)].ts
        if name is None:
            raise SchemaError(f"limit {m.group(1)!r} has no generated TypeScript name to fill a message")
        used.add(name)
        out.append(f"${{String({name})}}")
        pos = m.end()
    out.append(message[pos:].replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${"))
    return "`" + "".join(out) + "`", used


def ts_codes(model: Model) -> str:
    entries: list[str] = []
    messages: list[str] = []
    imports: set[str] = set()
    for c in model.codes:
        entries += ts_doc(c.meaning, "  ")
        entries.append(f"  {pascal(c.name)}: {ts_str(c.code)},")
        text, used = ts_message(model, c.message)
        imports |= used
        messages.append(f"  {c.code}: {text},")
    head = [f"// {HEADER}", "// Source: spec/schema/diagnostics.json.", ""]
    if imports:
        head += [f"import {{ {', '.join(sorted(imports))} }} from \"./limits.js\";", ""]
    return "\n".join([
        *head,
        "/** villanelle's diagnostic codes, by name (spec 2.4). */",
        "export const DiagnosticCode = {",
        *entries,
        "} as const;",
        "export type DiagnosticCode = (typeof DiagnosticCode)[keyof typeof DiagnosticCode];",
        "",
        "/** The base message of each code (spec 2.3: for people, not part of the contract). */",
        "export const MESSAGES: Readonly<Record<DiagnosticCode, string>> = {",
        *messages,
        "};",
        "",
    ])


def ts_kinds(model: Model) -> str:
    out = [f"// {HEADER}", "// Source: spec/schema/api.json \"kinds\".", ""]
    for k in model.kinds:
        name = pascal(k.name)
        out += ts_doc(f"The spec's {k.name} list: a string-literal type, so a literal narrows without an import.")
        one_line = f"export type {name} = {' | '.join(ts_str(v) for v in k.values)};"
        if len(one_line) <= 120:
            out.append(one_line)
        else:
            out += [f"export type {name} =", *(f"  | {ts_str(v)}" for v in k.values[:-1]), f"  | {ts_str(k.values[-1])};"]
        out.append("")
    return "\n".join(out)


def ts_limits(model: Model) -> str:
    out = [f"// {HEADER}", "// Source: spec/schema/api.json \"limits\", \"reserved names\" and \"patterns\".", ""]
    for c in model.limits:
        if c.ts:
            out += ts_doc(f"{c.name}: {c.means}.")
            out += [f"export const {c.ts} = {c.value};", ""]
    r = model.reserved
    if r.ts:
        out += ts_doc(f"{r.name}: {r.means}.")
        out += [f"export const {r.ts}: ReadonlySet<string> = new Set([{', '.join(ts_str(w) for w in r.value)}]);", ""]  # type: ignore[attr-defined]
    for p in model.patterns:
        if p.ts:
            out += ts_doc(f"{p.name}: {p.means}.")
            out += [f"export const {p.ts} = /{str(p.value).replace('/', chr(92) + '/')}/u;", ""]
    return "\n".join(out)


# --- Python --------------------------------------------------------------------------------------------------


def py_str(s: str) -> str:
    """A string literal as ruff format writes it: double quotes unless that would need more escapes."""
    body = json.dumps(s, ensure_ascii=False)[1:-1]
    if '"' in s and "'" not in s:
        return "'" + body.replace('\\"', '"') + "'"
    return '"' + body + '"'


def py_doc(text: str, indent: str = "    ") -> list[str]:
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
    if not text:
        return []
    lines = textwrap.wrap(text, 114 - len(indent))
    if len(lines) == 1:
        return [f'{indent}"""{lines[0]}"""']
    return [f'{indent}"""{lines[0]}', *(f"{indent}{line}" for line in lines[1:]), f'{indent}"""']


def py_message(model: Model, message: str) -> tuple[str, set[str]]:
    used: set[str] = set()
    if not PLACEHOLDER.search(message):
        return py_str(message), used
    out = []
    pos = 0
    for m in PLACEHOLDER.finditer(message):
        out.append(message[pos : m.start()].replace("{", "{{").replace("}", "}}"))
        name = model.limit_names[m.group(1)].py
        if name is None:
            raise SchemaError(f"limit {m.group(1)!r} has no generated Python name to fill a message")
        used.add(name)
        out.append("{" + name + "}")
        pos = m.end()
    out.append(message[pos:].replace("{", "{{").replace("}", "}}"))
    return "f" + py_str("".join(out)), used


def py_codes(model: Model) -> str:
    members: list[str] = []
    messages: list[str] = []
    imports: set[str] = set()
    for c in model.codes:
        members.append(f"    {upper_snake(c.name)} = {py_str(c.code)}")
        members += py_doc(c.meaning)
        text, used = py_message(model, c.message)
        imports |= used
        messages.append(f"        DiagnosticCode.{upper_snake(c.name)}: {text},")
    head = [f'"""{HEADER}', "", 'Source: spec/schema/diagnostics.json."""', "", "from collections.abc import Mapping",
            "from enum import StrEnum", "from types import MappingProxyType", "from typing import Final", ""]
    if imports:
        head += [f"from villanelle._api.limits import {', '.join(sorted(imports))}", ""]
    return "\n".join([
        *head,
        "",
        "class DiagnosticCode(StrEnum):",
        '    """villanelle\'s diagnostic codes, by name (spec 2.4)."""',
        "",
        *members,
        "",
        "",
        "MESSAGES: Final[Mapping[str, str]] = MappingProxyType(",
        "    {",
        *messages,
        "    }",
        ")",
        '"""The base message of each code (spec 2.3: for people, not part of the contract)."""',
        "",
    ])


def py_kinds(model: Model) -> str:
    head = f'"""{HEADER}\n\nSource: spec/schema/api.json "kinds" (token kind: grammar/Villanelle.g4)."""\n\nfrom enum import StrEnum'
    blocks = [head]
    for k in model.kinds:
        name = pascal(k.name)
        members = "\n".join(f"    {k.member_py(v)} = {py_str(v)}" for v in k.values)
        blocks.append(f'class {name}(StrEnum):\n    """The spec\'s {k.name} list."""\n\n{members}')
    return "\n\n\n".join(blocks) + "\n"


def py_limits(model: Model) -> str:
    out = [f'"""{HEADER}', "", 'Source: spec/schema/api.json "limits", "reserved names" and "patterns"."""', "",
           "import re", "from typing import Final", ""]
    for c in model.limits:
        if c.py:
            out += [f"{c.py}: Final = {c.value}", *py_doc(f"{c.name}: {c.means}.", ""), ""]
    r = model.reserved
    if r.py:
        out += [f"{r.py}: Final = frozenset({{{', '.join(py_str(w) for w in r.value)}}})", *py_doc(f"{r.name}: {r.means}.", ""), ""]  # type: ignore[attr-defined]
    for p in model.patterns:
        if p.py:
            # Python's $ also matches before a final newline: \Z is the end of the text, as the schema means.
            regex = str(p.value)[:-1] + "\\Z"
            out += [f'{p.py}: Final = re.compile(r"{regex}")', *py_doc(f"{p.name}: {p.means}. Ends in \\Z, not $.", ""), ""]
    while out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"


# --- writing -------------------------------------------------------------------------------------------------


def render(model: Model, lang: str) -> dict[str, str]:
    if lang == "ts":
        return {"codes.ts": ts_codes(model), "kinds.ts": ts_kinds(model), "limits.ts": ts_limits(model)}
    return {
        "__init__.py": f'"""{HEADER}"""\n',
        "codes.py": py_codes(model),
        "kinds.py": py_kinds(model),
        "limits.py": py_limits(model),
        # The folder is generated and never committed: ignore it from inside, as tools/gen.sh's own output is ignored.
        ".gitignore": f"# {HEADER}\n*\n",
    }


def write(files: dict[str, str], out: Path) -> None:
    """Write into a temp dir inside `out`, then move each file into place: no reader sees a half-written file."""
    out.mkdir(parents=True, exist_ok=True)
    tmp = Path(tempfile.mkdtemp(prefix=".tmp.", dir=out))
    try:
        for name, text in files.items():
            (tmp / name).write_text(text, encoding="utf-8")
        for name in files:
            os.replace(tmp / name, out / name)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv: list[str]) -> int:
    if len(argv) != 1 or argv[0] not in ("ts", "py", "--check"):
        print("usage: tools/gen-api.py <ts|py|--check>", file=sys.stderr)
        return 2
    try:
        api, diagnostics = read_schema()
        model = Model(api, diagnostics)
        if argv[0] == "--check":
            planted(api, diagnostics)
            with tempfile.TemporaryDirectory() as tmp:
                for lang in ("ts", "py"):
                    write(render(model, lang), Path(tmp) / lang)
            return 0
        write(render(model, argv[0]), OUT[argv[0]])
    except (SchemaError, KeyError, TypeError, ValueError, re.error) as e:
        print(f"gen-api.py: {type(e).__name__}: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

"""The loader: reads spec/schema/ into one checked, language-neutral model that every emitter renders (spec/codegen.md).

Nothing here knows a target language. It owns the three things every emitter shares, so none of them is written twice:

- the casing rule (spec/binding-guide.md rule 1): a spec name is lowercase words; ``words`` splits it and each emitter
  joins the words in its language's casing;
- the closed type grammar (spec/codegen.md section 2), parsed into ``Type`` trees whose every name resolves;
- the structural checks: variants cover their kind list, every generic name gets as many type arguments as it takes,
  the layer direction holds for every member type, error groups form a tree on the spec's two sorts, no two names
  derive one identifier (public names, each concept's members, each kind list's members).

Each closed list (traits, natures, found-by, code layers, ...) has one home, spec/schema/api.schema.json: the loader
reads it from there (``closed``). What differs by target language is not here: each emitter hands the loader a
``Language`` (its key, its casing, its error bases, what its public names are), so a new binding registers one
emitter and the loader is unchanged.

Python 3.9 standard library only (macOS ships 3.9), like the rest of tools/.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence, Tuple

REPO = Path(__file__).resolve().parent.parent.parent
SCHEMA = REPO / "spec" / "schema"
META = json.loads((SCHEMA / "api.schema.json").read_text(encoding="utf-8"))
GRAMMAR = REPO / "grammar" / "Villanelle.g4"
HEADER = "Generated by tools/gen-api.py from spec/schema/; do not edit. Never committed (owner, 2026-10-23)."


class SchemaError(Exception):
    pass


# --- the casing rule (binding guide rule 1): the one home of how a spec name splits ----------------------------------


def words(name: str) -> List[str]:
    parts = re.split(r"[ -]+", name.strip())
    if not parts or not all(re.fullmatch(r"[a-z0-9]+", p) for p in parts):
        raise SchemaError(f"not a spec name (lowercase words): {name!r}")
    return parts


def pascal(name: str) -> str:
    return "".join(w[0].upper() + w[1:] for w in words(name))


def camel(name: str) -> str:
    w = words(name)
    return w[0] + "".join(x[0].upper() + x[1:] for x in w[1:])


def snake(name: str) -> str:
    return "_".join(words(name))


def upper_snake(name: str) -> str:
    return "_".join(w.upper() for w in words(name))


# --- the closed type grammar (spec/codegen.md section 2) -------------------------------------------------------------

BUILTINS = ("text", "integer", "number", "boolean", "nothing", "absent")
PROTOCOL_BUILTINS = ("text", "integer", "number", "boolean", "json", "id", "null")
KEYWORDS = ("or", "of", "to", "and", "map", "function", "writable", "tuple")  # no name a type uses may hold one


def closed(*path: str) -> Tuple[str, ...]:
    """A closed list's one home: the enum at ``path`` under the meta-schema's $defs."""
    node = META["$defs"]
    for key in path:
        node = node[key]
    return tuple(node["enum"])


def type_name(name: str, what: str) -> None:
    """A name a type can use is spec words with no word of the type grammar in it (so a type parses one way)."""
    bad = [w for w in words(name) if w in KEYWORDS]
    if bad:
        raise SchemaError(f"{what} {name!r}: holds the type grammar's word {bad[0]!r}")


def is_type_name(name: str) -> bool:
    return not any(w in KEYWORDS for w in words(name))


# A schema regex must mean the same in JavaScript (/u) and Python re: no shorthand class whose set differs between the
# engines (\s \S \w \W \d \D \b \B), and no '"' (Python's raw string literal ends at it).
UNPORTABLE = re.compile(r'\\[sSwWdDbB]|"')


@dataclass(frozen=True)
class Type:
    """One parsed type. ``form`` is one of: name, list, union, map, function, tuple, literal."""

    form: str
    name: str = ""  # form name: the resolved name; literal: its text
    args: Tuple["Type", ...] = ()  # name: generic arguments; list: (item,); union: alternatives; map: (key, value);
    # function: (*params, result); tuple: items
    writable: bool = False  # map only

    @property
    def item(self) -> "Type":
        return self.args[0]

    def names(self) -> List[str]:
        out = [self.name] if self.form == "name" else []
        for a in self.args:
            out += a.names()
        return out

    def without_absent(self) -> "Type":
        if self.form != "union":
            return self
        rest = tuple(a for a in self.args if not (a.form == "name" and a.name in ("absent", "null")))
        return rest[0] if len(rest) == 1 else Type("union", args=rest)

    @property
    def may_be_absent(self) -> bool:
        return self.form == "union" and any(a.form == "name" and a.name in ("absent", "null") for a in self.args)


def tokenize(text: str) -> List[str]:
    out: List[str] = []
    for m in re.finditer(r'"[^"]*"|\(|\)|\[\]|[^\s()\[\]"]+|\S', text):
        out.append(m.group())
    return out


class TypeParser:
    """Recursive descent over the grammar; ``known`` is every name a type may use at that point."""

    def __init__(self, text: str, known: Sequence[str], *, protocol: bool = False) -> None:
        self.text, self.toks, self.pos, self.protocol = text, tokenize(text), 0, protocol
        self.known = sorted(known, key=lambda n: -len(n.split()))  # longest name first

    def fail(self, why: str) -> SchemaError:
        return SchemaError(f"type {self.text!r}: {why}")

    def peek(self) -> Optional[str]:
        return self.toks[self.pos] if self.pos < len(self.toks) else None

    def take(self, tok: str) -> bool:
        if self.peek() == tok:
            self.pos += 1
            return True
        return False

    def parse(self) -> Type:
        t = self.union()
        if self.peek() is not None:
            raise self.fail(f"unexpected {self.peek()!r}")
        return t

    def union(self) -> Type:
        alts = [self.postfix()]
        while self.take("or"):
            alts.append(self.postfix())
        return alts[0] if len(alts) == 1 else Type("union", args=tuple(alts))

    def postfix(self) -> Type:
        t = self.primary()
        while self.take("[]"):
            t = Type("list", args=(t,))
        return t

    def primary(self) -> Type:
        tok = self.peek()
        if tok is None:
            raise self.fail("ends early")
        if self.take("("):
            t = self.union()
            if not self.take(")"):
                raise self.fail("missing ')'")
            return t
        if tok.startswith('"'):
            if not self.protocol:
                raise self.fail("a literal is only for the adapter protocol")
            self.pos += 1
            return Type("literal", name=tok[1:-1])
        if tok == "function" and not self.protocol:
            self.pos += 1
            params: List[Type] = []
            if self.take("of"):
                params.append(self.postfix())
                while self.take("and"):
                    params.append(self.postfix())
            if not self.take("to"):
                raise self.fail("'function' needs 'to <type>'")
            return Type("function", args=(*params, self.union()))
        if tok == "tuple" and self.protocol:
            self.pos += 1
            if not self.take("of"):
                raise self.fail("'tuple' needs 'of'")
            items = [self.postfix()]
            while self.take("and"):
                items.append(self.postfix())
            return Type("tuple", args=tuple(items))
        if tok in ("writable", "map"):
            writable = self.take("writable")
            if not (self.take("map") and self.take("of")):
                raise self.fail("expected 'map of'")
            first = self.postfix()
            if self.take("to"):
                return Type("map", args=(first, self.postfix()), writable=writable)
            return Type("map", args=(Type("name", name="text"), first), writable=writable)
        return self.name()

    def name(self) -> Type:
        for known in self.known:
            n = len(known.split())
            if [t for t in self.toks[self.pos : self.pos + n]] == known.split():
                self.pos += n
                args: List[Type] = []
                if self.peek() == "of" and known not in BUILTINS and known not in PROTOCOL_BUILTINS:
                    self.pos += 1
                    args.append(self.postfix())
                    while self.take("and"):
                        args.append(self.postfix())
                return Type("name", name=known, args=tuple(args))
        raise self.fail(f"{' '.join(self.toks[self.pos:self.pos + 3])!r}... names nothing the schema defines")


# --- the model ---------------------------------------------------------------------------------------------------------


@dataclass
class Param:
    name: str
    type: Type
    optional: bool = False
    passed: str = "position"  # position | keyword (Python keyword-only) | option (TS options object, Python kw-only)


@dataclass
class Member:
    name: str
    member: str  # property | method
    type: Type  # a property's type, a method's result
    params: List[Param] = field(default_factory=list)
    optional: bool = False  # options records: the property may be left out
    trait: Optional[str] = None
    io: bool = False
    errors: List[str] = field(default_factory=list)
    order: str = ""
    options: Optional[str] = None
    type_parameters: List[str] = field(default_factory=list)
    note: str = ""


TRAITS = closed("member", "properties", "trait")
NATURES = closed("concept", "properties", "nature")
PASSED = closed("param", "properties", "passed")
SORTS = closed("errorGroup", "properties", "sort")
LANGUAGES = tuple(META["$defs"]["languages"]["items"]["enum"])


@dataclass(frozen=True)
class Language:
    """What one target language contributes to the shared model: the loader asks, it never knows a language itself.

    ``key`` names the language in the schema (``ts``, ``py``: the per-language keys of error groups, factories,
    modules and the argument type message); ``sep`` joins a module path; ``function_case`` spells a free function;
    ``error_bases`` are the classes a root error group may extend or be; ``public_kind`` says whether a concept's
    public name is a type, a value or both in this language."""

    key: str
    sep: str
    function_case: Callable[[str], str]
    error_bases: Tuple[str, ...]
    public_kind: Callable[["Model", Optional["Concept"]], str]  # None: an enumeration or a generated class
    # Public names a trait's idiom adds in this language, as (module, identifier, what): Python's collect trait is a
    # context manager class, `Collecting`, beside the concept that has it.
    trait_names: Callable[["Model"], List[Tuple[str, str, str]]] = lambda model: []


@dataclass
class Concept:
    name: str
    layer: str
    nature: str
    members: List[Member]
    variant_of: Optional[str] = None
    kind: Optional[str] = None
    variants: List[str] = field(default_factory=list)
    kind_list: Optional[str] = None
    except_kinds: List[str] = field(default_factory=list)
    extends: Optional[Type] = None
    type_parameters: List[str] = field(default_factory=list)
    match_args: List[str] = field(default_factory=list)
    languages: Tuple[str, ...] = LANGUAGES
    module: Optional[str] = None
    is_: Optional[str] = None  # named type: text | native
    brand: bool = False
    pattern: Optional[str] = None
    callback: Optional[Type] = None
    note: str = ""
    template: Optional[str] = None  # named type: its form, '{text}' standing for any text

    @property
    def is_union(self) -> bool:
        return bool(self.variants)


@dataclass
class KindList:
    name: str
    layer: str
    values: List[str]
    sort: str  # variant set | tag
    variants: Dict[str, str]
    tag_of: List[str]
    from_grammar: bool = False
    languages: Tuple[str, ...] = LANGUAGES
    note: str = ""


@dataclass
class Constant:
    name: str  # the constant's spec name ("max nesting")
    layer: str
    value: object  # int, list of words, or a regex text
    sort: str  # limit | words | pattern
    means: str
    about: str = ""  # the limit's or pattern's own spec name
    code: str = ""  # a limit: the diagnostic code that reports going past it


@dataclass
class ErrorGroup:
    name: str
    sort: str  # base | expected outcome | program bug
    parent: Optional[str]
    raised_when: str
    fields: List[Tuple[str, Type]]  # parsed once the concepts are known (Model.__init__)
    message: Dict[str, object]
    cause: Optional[str]
    base: Dict[str, Dict[str, str]]  # language -> {"base": X} or {"builtin": X}
    note: str = ""

    def builtin(self, lang: str) -> Optional[str]:
        return self.base.get(lang, {}).get("builtin")


@dataclass
class Function:
    name: str
    layer: str
    params: List[Param]
    returns: Type
    errors: List[str]
    factory: Optional[Dict[str, str]] = None
    module: Dict[str, str] = field(default_factory=dict)  # language -> adapter module; empty: the layer's namespace
    options: Optional[str] = None
    note: str = ""


@dataclass
class Code:
    code: str
    name: str
    layer: str
    found_by: List[str]
    reason: Optional[str]
    message: str
    meaning: str
    summary: str = ""
    placed_at: str = ""


FOUND_BY = tuple(META["$defs"]["diagnostics"]["properties"]["codes"]["items"]["properties"]["found by"]["items"]["enum"])
CODE_LAYERS = tuple(META["$defs"]["diagnostics"]["properties"]["codes"]["items"]["properties"]["layer"]["enum"])
PLACEHOLDER = re.compile(r"\{([a-z][a-z -]*)\}")


@dataclass
class Layer:
    name: str
    holds: str
    may_import: List[str]
    namespace: str  # package | own


class Model:
    def __init__(self, api: dict, diagnostics: dict, protocol: dict, languages: Sequence[Language]) -> None:
        self.languages = {lang.key: lang for lang in languages}
        if sorted(self.languages) != sorted(LANGUAGES):
            raise SchemaError(f"the emitters' languages {sorted(self.languages)} are not the meta-schema's {sorted(LANGUAGES)}")
        self.package = str(api["package"])
        words(self.package)
        self.layers = [Layer(l["name"], l["holds"], list(l["may import"]), l["namespace"]) for l in api["layers"]]
        self.layer = {l.name: l for l in self.layers}
        self.layer_direction = str(api["layer direction"])

        self.kinds: List[KindList] = []
        for name, raw in api["kinds"].items():
            words(name)
            self._layer(raw["layer"], f"kind list {name!r}")
            from_grammar = raw.get("values from") == "grammar"
            values = grammar_tokens() if from_grammar else [str(v) for v in raw["values"]]
            if not values or len(set(values)) != len(values):
                raise SchemaError(f"kind list {name!r}: values must be a non-empty list without repeats")
            for v in values:
                if from_grammar:
                    if not re.fullmatch(r"[A-Z][A-Z0-9_]*", v):
                        raise SchemaError(f"kind list {name!r}: {v!r} is not a grammar token name")
                else:
                    words(v)
            self.kinds.append(KindList(name, raw["layer"], values, raw["sort"], dict(raw.get("variants", {})),
                                       list(raw.get("tag of", [])), from_grammar, tuple(raw.get("languages", LANGUAGES)),
                                       raw.get("note", "")))
        self.kind = {k.name: k for k in self.kinds}
        for k in self.kinds:
            type_name(k.name, "kind list")

        self.keywords: List[Tuple[str, str]] = [(k["word"], k["statement kind"]) for k in api["keywords"]]
        for word, sk in self.keywords:
            words(word)
            if sk not in self.kind["statement kind"].values:
                raise SchemaError(f"keyword {word!r}: {sk!r} is no statement kind")

        self.constants: List[Constant] = []
        for raw in api["limits"]:
            if not isinstance(raw["value"], int):
                raise SchemaError(f"limit {raw['name']!r}: value must be an integer")
            self.constants.append(Constant(raw["constant"], raw["layer"], raw["value"], "limit", raw["means"], raw["name"], raw["code"]))
        r = api["reserved names"]
        if r.get("words from") != "keywords":
            raise SchemaError("reserved names: 'words from' must be 'keywords' (the keywords' one home)")
        self.constants.append(Constant(r["constant"], r["layer"], [w for w, _ in self.keywords], "words", r["means"], "reserved names"))
        for name, raw in api["patterns"].items():
            regex = raw["regex"]
            if not (regex.startswith("^") and regex.endswith("$")):
                raise SchemaError(f"pattern {name!r}: regex must be anchored with ^ and $")
            re.compile(regex)
            bad = UNPORTABLE.search(regex)
            if bad:
                raise SchemaError(f"pattern {name!r}: {bad.group()!r} means different things in JavaScript and Python; write the class out")
            self.constants.append(Constant(raw["constant"], raw["layer"], regex, "pattern", raw["means"], name))
        for c in self.constants:
            words(c.name)
            self._layer(c.layer, f"constant {c.name!r}")
        self.limit = {c.about: c for c in self.constants if c.sort == "limit"}

        self.argument_type_message: Dict[str, str] = {k: api["argument type error message"][k] for k in self.languages}
        for lang, template in self.argument_type_message.items():
            got = set(PLACEHOLDER.findall(template))
            if got != {"member", "parameter", "got"}:
                raise SchemaError(f"argument type error message ({lang}): placeholders {sorted(got)}, want member, parameter, got")
        self.argument_type_rule = api["argument type error message"]

        # Concepts first by name, so every type can resolve against the whole set.
        raw_concepts = api["concepts"]
        self.concepts: List[Concept] = []
        seen = set()
        for c in raw_concepts:
            type_name(c["name"], "concept")
            for tp in c.get("type parameters", []):
                type_name(tp, f"concept {c['name']!r} type parameter")
            if c["name"] in seen:
                raise SchemaError(f"concept {c['name']!r} listed twice")
            seen.add(c["name"])
        self.groups = [self._group(g) for g in api["error groups"]]
        self.group = {g.name: g for g in self.groups}
        # An error group is a type name only when its name holds no word of the type grammar (a program bug's group,
        # 'index out of range', is never a value's type).
        names_known = (list(BUILTINS) + [k.name for k in self.kinds] + ["diagnostic code"] + list(seen)
                       + [g.name for g in self.groups if is_type_name(g.name)])
        self._known = names_known
        # How many type arguments each name takes: a concept its type parameters, every other name none.
        self._arity = {n: 0 for n in names_known}
        self._arity.update({c["name"]: len(c.get("type parameters", [])) for c in raw_concepts})
        for g in self.groups:
            g.fields = [(f, self.parse(str(t), f"error group {g.name!r} field {f!r}")) for f, t in g.fields]
        for c in raw_concepts:
            self.concepts.append(self._concept(c))
        self.concept = {c.name: c for c in self.concepts}
        self.functions = [self._function(f) for f in api["free functions"]]

        self.codes = [self._code(c) for c in diagnostics["codes"]]
        self.retired = [str(r["code"]) for r in diagnostics.get("retired", [])]
        self.code_ranges = dict(diagnostics.get("ranges", {}))
        self.code_rules = list(diagnostics.get("rules", []))
        live = {c.code for c in self.codes}
        if len(live) != len(self.codes):
            raise SchemaError("a diagnostic code is listed twice")
        if live & set(self.retired):
            raise SchemaError(f"retired codes still listed: {sorted(live & set(self.retired))}")

        self.protocol = Protocol(protocol)
        self._check()

    # --- reading ---

    def _layer(self, name: str, what: str) -> None:
        if name not in self.layer:
            raise SchemaError(f"{what}: layer {name!r} is no layer")

    def parse(self, text: str, where: str, extra: Sequence[str] = ()) -> Type:
        try:
            t = TypeParser(text, list(self._known) + list(extra)).parse()
        except SchemaError as e:
            raise SchemaError(f"{where}: {e}") from None
        self._check_arity(t, f"{where}: type {text!r}", extra)
        return t

    def _check_arity(self, t: Type, where: str, type_params: Sequence[str]) -> None:
        """Every name gets exactly as many type arguments as it takes (a kind list, group or builtin: none)."""
        if t.form == "name":
            want = 0 if t.name in type_params else self._arity.get(t.name, 0)
            if len(t.args) != want:
                raise SchemaError(f"{where}: {t.name!r} takes {want} type arguments, given {len(t.args)}")
        for a in t.args:
            self._check_arity(a, where, type_params)

    def _params(self, raw: list, where: str, extra: Sequence[str]) -> List[Param]:
        out = []
        for p in raw:
            words(p["name"])
            passed = p.get("passed", "position")
            if passed not in PASSED:
                raise SchemaError(f"{where}: parameter {p['name']!r}: passed {passed!r}")
            out.append(Param(p["name"], self.parse(p["type"], f"{where} ({p['name']})", extra), bool(p.get("optional")), passed))
        return out

    def _concept(self, c: dict) -> Concept:
        where = f"concept {c['name']!r}"
        if c["nature"] not in NATURES:
            raise SchemaError(f"{where}: nature {c['nature']!r} is not one of {NATURES}")
        self._layer(c["layer"], where)
        tps = list(c.get("type parameters", []))
        members = []
        for m in c.get("members", []):
            words(m["name"])
            mw = f"{where}, member {m['name']!r}"
            for tp in m.get("type parameters", []):
                type_name(tp, f"{mw} type parameter")
            if m["member"] not in ("property", "method"):
                raise SchemaError(f"{mw}: member {m['member']!r}")
            if m.get("trait") is not None and m["trait"] not in TRAITS:
                raise SchemaError(f"{mw}: trait {m['trait']!r} is not one of {TRAITS}")
            mtps = list(m.get("type parameters", []))
            extra = tps + mtps
            if m["member"] == "property":
                t = self.parse(m["type"], mw, extra)
                params: List[Param] = []
            else:
                t = self.parse(m["returns"], mw, extra)
                params = self._params(m.get("params", []), mw, extra)
            members.append(Member(m["name"], m["member"], t, params, bool(m.get("optional")), m.get("trait"), bool(m.get("io")),
                                  list(m.get("errors", [])), str(m.get("order", "")), m.get("options"), mtps, m.get("note", "")))
        return Concept(
            c["name"], c["layer"], c["nature"], members, c.get("variant of"), c.get("kind"), list(c.get("variants", [])),
            c.get("kind list"), list(c.get("except", [])),
            self.parse(c["extends"], f"{where} extends") if "extends" in c else None, tps, list(c.get("match args", [])),
            tuple(c.get("languages", LANGUAGES)), c.get("module"), c.get("is"), bool(c.get("brand")), c.get("pattern"),
            self.parse(c["type"], f"{where} type") if "type" in c else None, c.get("note", ""), c.get("template"))

    def _group(self, g: dict) -> ErrorGroup:
        words(g["name"])  # a group whose name holds a grammar word ('index out of range') is no type name: see _known
        if g["sort"] not in SORTS:
            raise SchemaError(f"error group {g['name']!r}: sort {g['sort']!r}")
        base = {lang: dict(g[lang]) for lang in self.languages if lang in g}
        return ErrorGroup(g["name"], g["sort"], g.get("parent"), g["raised when"],
                          [(f["name"], f["type"]) for f in g.get("fields", [])], dict(g.get("message", {})), g.get("cause"), base,
                          g.get("note", ""))

    def _function(self, f: dict) -> Function:
        where = f"free function {f['name']!r}"
        words(f["name"])
        self._layer(f["layer"], where)
        return Function(f["name"], f["layer"], self._params(f.get("params", []), where, ()), self.parse(f["returns"], where),
                        list(f.get("errors", [])), f.get("factory"), dict(f.get("module", {})), f.get("options"), f.get("note", ""))

    def _code(self, c: dict) -> Code:
        if not re.fullmatch(r"E[0-9]{4}", c["code"]):
            raise SchemaError(f"bad code {c['code']!r}")
        words(c["name"])
        if c["layer"] not in CODE_LAYERS:
            raise SchemaError(f"{c['code']}: layer {c['layer']!r} is not one of {CODE_LAYERS}")
        for fb in c["found by"]:
            if fb not in FOUND_BY:
                raise SchemaError(f"{c['code']}: found by {fb!r} is not one of {FOUND_BY}")
        reason = c["unreadable reason"]
        if reason is not None and reason not in self.kind["unreadable reason"].values:
            raise SchemaError(f"{c['code']}: unreadable reason {reason!r} is no unreadable reason")
        for ph in PLACEHOLDER.findall(c["message"]):
            if ph not in self.limit:
                raise SchemaError(f"{c['code']}: message names {{{ph}}}, which is no limit in api.json")
        return Code(c["code"], c["name"], c["layer"], list(c["found by"]), reason, c["message"], c["meaning"], c["summary"], c["placed at"])

    # --- checking ---

    def layer_of(self, name: str) -> Optional[str]:
        if name in self.concept:
            return self.concept[name].layer
        if name in self.kind:
            return self.kind[name].layer
        if name == "diagnostic code":
            return "shared"
        if name in self.group:
            return "shared"
        return None

    def _check(self) -> None:
        c_by = self.concept
        for c in self.concepts:
            where = f"concept {c.name!r}"
            if c.variant_of:
                union = c_by.get(c.variant_of)
                if union is None or c.name not in union.variants:
                    raise SchemaError(f"{where}: its union {c.variant_of!r} does not list it in 'variants'")
            if c.extends is not None and c.extends.name not in c_by:
                raise SchemaError(f"{where}: extends {c.extends.name!r}, which is no concept")  # its arity: parse()
            if c.nature == "named type" and c.is_ not in ("text", "native"):
                raise SchemaError(f"{where}: a named type is 'text' or 'native'")
            if c.nature == "callback" and (c.callback is None or c.callback.form != "function"):
                raise SchemaError(f"{where}: a callback's type is a function type")
            if c.module is not None and c.layer != "io":
                raise SchemaError(f"{where}: only the io layer has adapter modules")
            for lang in c.languages:
                if lang not in self.languages:
                    raise SchemaError(f"{where}: language {lang!r}")
            self._members_distinct(c)
            if c.is_union:
                lst = self.kind.get(c.kind_list or "")
                if lst is None:
                    raise SchemaError(f"{where}: 'kind list' {c.kind_list!r} is no kind list")
                want = sorted(v for v in lst.values if v not in c.except_kinds)
                got = []
                for v in c.variants:
                    variant = c_by.get(v)
                    if variant is None or variant.variant_of != c.name:
                        raise SchemaError(f"{where}: variant {v!r} is no concept naming it in 'variant of'")
                    got.append(str(variant.kind))
                if sorted(got) != want:
                    raise SchemaError(f"{where}: its variants' kinds {sorted(got)} are not the {lst.name} list {want}")
            for m in c.members:
                self._direction(c.layer, m.type, f"{where}, member {m.name!r}", c.type_parameters + m.type_parameters)
                for p in m.params:
                    self._direction(c.layer, p.type, f"{where}, member {m.name!r}", c.type_parameters + m.type_parameters)
                for e in m.errors:
                    if e not in self.group:
                        raise SchemaError(f"{where}, member {m.name!r}: error {e!r} is no error group")
                if m.options is not None and (m.options not in c_by or c_by[m.options].nature != "options"):
                    raise SchemaError(f"{where}, member {m.name!r}: options {m.options!r} is no options concept")
                if any(p.passed == "option" for p in m.params) != (m.options is not None):
                    raise SchemaError(f"{where}, member {m.name!r}: option parameters and 'options' go together")
            if c.match_args:
                have = {m.name for m in self.all_members(c)}
                for a in c.match_args:
                    if a not in have:
                        raise SchemaError(f"{where}: match args {a!r} is no member")
        for lst in self.kinds:
            if not lst.from_grammar:
                for case in (pascal, upper_snake):
                    self._distinct([case(v) for v in lst.values], f"kind list {lst.name!r}")
            for value, concept in lst.variants.items():
                if concept not in c_by or c_by[concept].kind != value:
                    raise SchemaError(f"kind list {lst.name!r}: {value!r} maps to {concept!r}, which is no concept of that kind")
            if lst.sort == "variant set" and sorted(lst.variants) != sorted(lst.values):
                raise SchemaError(f"kind list {lst.name!r}: a variant set maps every value to its concept")
            for concept in lst.tag_of:
                if concept not in c_by:
                    raise SchemaError(f"kind list {lst.name!r}: tag of {concept!r}, which is no concept")
        for g in self.groups:
            where = f"error group {g.name!r}"
            if g.parent is not None:
                parent = self.group.get(g.parent)
                if parent is None:
                    raise SchemaError(f"{where}: parent {g.parent!r} is no error group")
                if g.sort == "program bug" or parent.sort == "program bug":
                    raise SchemaError(f"{where}: a program bug is under no group, and no group is under one (spec 2.8)")
            elif g.sort == "expected outcome":
                raise SchemaError(f"{where}: every expected outcome sits under the base (spec 2.8)")
            for key, lang in self.languages.items():
                if g.parent is None:
                    b = g.base.get(key)
                    if not b or len(b) != 1 or next(iter(b.values())) not in lang.error_bases:
                        raise SchemaError(f"{where}: needs {key} 'base' or 'builtin' from {lang.error_bases}")
                elif g.base.get(key):
                    raise SchemaError(f"{where}: a group with a parent takes its base from it")
            self._distinct([f for f, _ in g.fields], where)
            for fname, ftype in g.fields:
                words(fname)
                self._direction("shared", ftype, where, ())
            if not all(g.builtin(lang) for lang in self.languages) and "given" not in g.message and "template" not in g.message:
                raise SchemaError(f"{where}: a class needs 'message': given or a template")
            t = g.message.get("template")
            if t is not None:
                fields = dict(g.fields)
                for ph in PLACEHOLDER.findall(str(t)):
                    if ph.endswith(" message") and ph[: -len(" message")] in fields:
                        continue  # the message of a field that has one
                    if ph not in fields:
                        raise SchemaError(f"{where}: template names {{{ph}}}, which is no field")
                    if fields[ph].form != "list":
                        raise SchemaError(f"{where}: template names {{{ph}}}, which is no list (a placeholder joins a list)")
        for f in self.functions:
            for p in f.params:
                self._direction(f.layer, p.type, f"free function {f.name!r}", ())
            self._direction(f.layer, f.returns, f"free function {f.name!r}", ())
            if f.factory is not None and f.factory.get("of") not in c_by:
                raise SchemaError(f"free function {f.name!r}: factory of {f.factory.get('of')!r}, which is no concept")
            for e in f.errors:
                if e not in self.group:
                    raise SchemaError(f"free function {f.name!r}: error {e!r} is no error group")
        self._spellings()

    def _direction(self, layer: str, t: Type, where: str, type_params: Sequence[str]) -> None:
        allowed = {layer, *self.layer[layer].may_import}
        for n in t.names():
            if n in BUILTINS or n in type_params:
                continue
            got = self.layer_of(n)
            if got is None:
                raise SchemaError(f"{where}: type {n!r} names nothing the schema defines")
            if got not in allowed:
                raise SchemaError(f"{where}: names {n!r} of the {got} layer, which the {layer} layer may not import (layer direction)")

    def _spellings(self) -> None:
        """No two public names derive the same identifier in one namespace (the casing rule must stay one-to-one)."""
        for lang in self.languages:
            seen: Dict[Tuple[str, str], str] = {}
            for module, name, what in self.public(lang):
                if (module, name) in seen:
                    raise SchemaError(f"{lang}: two public names both spell {name!r} in {module}")
                seen[(module, name)] = what

    @staticmethod
    def _distinct(names: List[str], where: str) -> None:
        seen = set()
        for n in names:
            if n in seen:
                raise SchemaError(f"{where}: two names both spell {n!r}")
            seen.add(n)

    def _members_distinct(self, c: Concept) -> None:
        """A concept's members are listed once and no two spell one identifier in any casing (camel, snake)."""
        own = [m.name for m in self.all_members(c) if not (c.variant_of and m.name == "kind")]
        where = f"concept {c.name!r} members"
        self._distinct(own, where)
        for case in (camel, snake):
            self._distinct([case(n) for n in own], where)

    # --- views the emitters share -------------------------------------------------------------------------------

    def all_members(self, c: Concept) -> List[Member]:
        """Every member a concept has: its union's, then its own (a variant), after the members it extends."""
        out: List[Member] = []
        if c.variant_of:
            out += [m for m in self.concept[c.variant_of].members if m.name != "kind"]
        if c.extends is not None:
            out += self.all_members(self.concept[c.extends.name])
        return out + list(c.members)

    def kind_list_of(self, c: Concept) -> str:
        """The kind list a concept's kind member is typed by (a variant's, or a fixed-kind record's)."""
        for m in self.all_members(c) + ([m for m in self.concept[c.variant_of].members] if c.variant_of else []):
            if m.name == "kind" and m.type.form == "name":
                return m.type.name
        raise SchemaError(f"concept {c.name!r} has a kind but no kind member typed by a kind list")

    def module(self, layer: str, sep: str) -> str:
        return self.package if self.layer[layer].namespace == "package" else f"{self.package}{sep}{layer}"

    def concept_module(self, c: Concept, lang: str) -> str:
        sep = self.languages[lang].sep
        if c.module is not None:
            return f"{self.package}{sep}{c.module}"
        return self.module(c.layer, sep)

    def function_module(self, f: Function, lang: str) -> Optional[str]:
        sep = self.languages[lang].sep
        if f.module:
            return f"{self.package}{sep}{f.module[lang]}" if lang in f.module else None
        return self.module(f.layer, sep)

    def constructed(self, c: Concept, lang: str) -> bool:
        """The concept is a class a program constructs in ``lang``: a free function is its constructor there."""
        return any((f.factory or {}).get("of") == c.name and (f.factory or {}).get(lang) == "constructor" for f in self.functions)

    def public(self, lang: str) -> List[Tuple[str, str, str]]:
        """Every public name of one binding: (module, identifier, what), what being 'type', 'value' or 'both'."""
        language = self.languages[lang]
        sep = language.sep
        out: List[Tuple[str, str, str]] = []
        for c in self.concepts:
            if lang not in c.languages or c.is_ == "native":
                continue  # a native type is the language's own
            out.append((self.concept_module(c, lang), pascal(c.name), language.public_kind(self, c)))
        enum = language.public_kind(self, None)  # what an enumeration or a class of the generated code is
        for k in self.kinds:
            if lang in k.languages:
                out.append((self.module(k.layer, sep), pascal(k.name), enum))
        out.append((self.package, pascal("diagnostic code"), enum))
        for g in self.groups:
            if not g.builtin(lang):
                out.append((self.package, pascal(g.name), enum))
        for f in self.functions:
            mod = self.function_module(f, lang)
            if mod is None:
                continue
            fac = (f.factory or {}).get(lang)
            if fac == "constructor":
                continue  # the class is the factory
            name = self.package if fac == "package function" else language.function_case(f.name)
            out.append((mod, name, "value"))
        for c in self.constants:
            out.append((self.module(c.layer, sep), upper_snake(c.name), "value"))
        return sorted(out + language.trait_names(self))


def grammar_tokens() -> List[str]:
    """The lexer rule names of grammar/Villanelle.g4 in declaration order, fragments aside: the token kinds."""
    text = GRAMMAR.read_text(encoding="utf-8")
    names: List[str] = []
    for line in text.splitlines():
        code = re.sub(r"'(?:\\.|[^'\\])*'", "''", line)  # literals may hold ':' or ';'
        code = code.split("//", 1)[0]
        if code.lstrip().startswith("fragment"):
            continue
        for m in re.finditer(r"(?:^|;)\s*([A-Z][A-Z0-9_]*)\s*:", code):
            names.append(m.group(1))
    if not names:
        raise SchemaError(f"no lexer rules found in {GRAMMAR}")
    return names


# --- the adapter protocol (spec/conformance.md 4; spec/codegen.md section 5) ------------------------------------------


@dataclass
class Shape:
    name: str
    fields: Dict[str, Type]
    optional: List[str]
    by_kind: Dict[str, Dict[str, Type]]
    tuple_: Optional[List[Type]]
    one_of: Dict[str, Type]
    note: str
    other_kinds: List[str] = field(default_factory=list)  # with by_kind: every kind the shape takes

    @property
    def kinds(self) -> List[str]:
        return list(self.by_kind) + self.other_kinds


@dataclass
class Request:
    op: str
    params: Dict[str, Type]
    optional: List[str]
    result: Type
    level: str
    note: str = ""
    params_note: str = ""


class Protocol:
    def __init__(self, raw: dict) -> None:
        self.version = int(raw["protocol"])
        names = [s["name"] for s in raw["shapes"]] + [r["name"] for r in raw["results"]]
        for n in names:
            words(n)
        if len(set(names)) != len(names):
            raise SchemaError("protocol: a shape is listed twice")
        known = list(PROTOCOL_BUILTINS) + ["position"] + names

        def parse(text: str, where: str) -> Type:
            try:
                return TypeParser(text, known, protocol=True).parse()
            except SchemaError as e:
                raise SchemaError(f"protocol {where}: {e}") from None

        self.shapes: List[Shape] = []
        for s in list(raw["shapes"]) + list(raw["results"]):
            fields = {k: parse(v, f"{s['name']}.{k}") for k, v in s.get("fields", {}).items()}
            by_kind = {kind: {k: parse(v, f"{s['name']} {kind}.{k}") for k, v in extra.items()}
                       for kind, extra in s.get("by kind", {}).items()}
            tup = [parse(t, f"{s['name']}[{i}]") for i, t in enumerate(s["tuple"])] if "tuple" in s else None
            one_of = {k: parse(v, f"{s['name']}.{k}") for k, v in s.get("one of", {}).items()}
            if sum(map(bool, (fields or by_kind, tup, one_of))) != 1:
                raise SchemaError(f"protocol shape {s['name']!r}: exactly one of fields, tuple, one of")
            for o in s.get("optional", []):
                if o not in fields:
                    raise SchemaError(f"protocol shape {s['name']!r}: optional {o!r} is no field")
            other = list(s.get("other kinds", []))
            if by_kind and ("kind" not in fields or not other or set(other) & set(by_kind)):
                raise SchemaError(f"protocol shape {s['name']!r}: 'by kind' needs a kind field and 'other kinds', the rest of its kinds")
            if other and not by_kind:
                raise SchemaError(f"protocol shape {s['name']!r}: 'other kinds' goes with 'by kind'")
            self.shapes.append(Shape(s["name"], fields, list(s.get("optional", [])), by_kind, tup, one_of, s.get("note", ""), other))
        self.shape = {s.name: s for s in self.shapes}
        self.requests = []
        for r in raw["requests"]:
            words(r["op"])
            params = {k: parse(v, f"{r['op']}.{k}") for k, v in r["params"].items()}
            for o in r.get("optional", []):
                if o not in params:
                    raise SchemaError(f"protocol request {r['op']!r}: optional {o!r} is no parameter")
            for k in params:
                if f"`{k}`" not in r.get("params note", ""):
                    raise SchemaError(f"protocol request {r['op']!r}: its params note does not describe `{k}`")
            self.requests.append(Request(r["op"], params, list(r.get("optional", [])), parse(r["result"], r["op"]), r["level"],
                                         r.get("note", ""), r.get("params note", "")))
        self.edit_members = list(raw["edit members"])
        self.readers = list(raw["readers"])


# --- reading the files -------------------------------------------------------------------------------------------------


def read_json(name: str) -> dict:
    with (SCHEMA / name).open(encoding="utf-8") as f:
        return json.load(f)


def read_schema() -> Tuple[dict, dict, dict]:
    return read_json("api.json"), read_json("diagnostics.json"), read_json("protocol.json")


def planted(api: dict, diagnostics: dict, protocol: dict, languages: Sequence[Language]) -> List[str]:
    """Each check still bites: a broken copy of the schema must be refused (as tools/planted/ does for the grammar)."""

    def concept(a: dict, name: str) -> dict:
        return next(c for c in a["concepts"] if c["name"] == name)

    def member(a: dict, cname: str, mname: str) -> dict:
        return next(m for m in concept(a, cname)["members"] if m["name"] == mname)

    plants = {
        "variant missing": lambda a, d, p: concept(a, "variable")["variants"].remove("override variable"),
        "wrong kind": lambda a, d, p: concept(a, "set line").__setitem__("kind", "use"),
        "bad parent": lambda a, d, p: a["error groups"][1].__setitem__("parent", "no such group"),
        "unresolved type": lambda a, d, p: member(a, "document", "block").__setitem__("type", "writen block"),
        "type grammar": lambda a, d, p: member(a, "document", "block").__setitem__("type", "written block or"),
        "layer direction": lambda a, d, p: member(a, "document", "block").__setitem__("type", "rendered block"),
        "free text type": lambda a, d, p: member(a, "copy", "via").__setitem__("type", "the steps, innermost first"),
        "bug under the base": lambda a, d, p: next(g for g in a["error groups"] if g["name"] == "detached error").__setitem__("parent", "villanelle error"),
        "unknown trait": lambda a, d, p: member(a, "place", "people form").__setitem__("trait", "display"),
        "spelling collision": lambda a, d, p: a["concepts"].append({"name": "Statement kind".lower(), "layer": "written", "nature": "record", "members": []}),
        "bad found by": lambda a, d, p: d["codes"][0].__setitem__("found by", ["render"]),
        "protocol type": lambda a, d, p: p["shapes"][1]["fields"].__setitem__("path", "txt"),
        "generic arity": lambda a, d, p: member(a, "document", "block").__setitem__("type", "resolution of variable and text"),
        "arguments on a plain name": lambda a, d, p: member(a, "document", "block").__setitem__("type", "statement of text"),
        "generic without arguments": lambda a, d, p: member(a, "document", "block").__setitem__("type", "resolution"),
        "keyword in a name": lambda a, d, p: a["concepts"].append({"name": "left or right", "layer": "written", "nature": "record"}),
        "member spelling collision": lambda a, d, p: concept(a, "place")["members"].append(
            dict(member(a, "place", "resolved path"), name="resolved-path")),
        "member listed twice": lambda a, d, p: concept(a, "place")["members"].append(dict(member(a, "place", "resolved path"))),
        "kind value collision": lambda a, d, p: a["kinds"]["walk control"]["values"].extend(["zed x", "zed-x"]),
        "unportable regex": lambda a, d, p: a["patterns"]["variable name"].__setitem__("regex", "^\\w+$"),
        "template on a non-list": lambda a, d, p: next(g for g in a["error groups"] if g["name"] == "read error").__setitem__(
            "message", {"template": "{paths}"}) or next(g for g in a["error groups"] if g["name"] == "read error")["fields"][0].__setitem__("type", "text"),
    }
    # The refusal each newer plant must give, so it is caught by its own check and not by an earlier one by chance.
    reason = {
        "generic arity": "takes 1 type arguments, given 2",
        "arguments on a plain name": "takes 0 type arguments, given 1",
        "generic without arguments": "takes 1 type arguments, given 0",
        "keyword in a name": "type grammar's word 'or'",
        "member spelling collision": "both spell 'resolvedPath'",
        "member listed twice": "both spell 'resolved path'",
        "kind value collision": "both spell 'ZedX'",
        "unportable regex": "means different things",
        "template on a non-list": "which is no list",
    }
    caught = []
    for name, plant in plants.items():
        broken = [json.loads(json.dumps(x)) for x in (api, diagnostics, protocol)]
        plant(*broken)
        try:
            Model(*broken, languages)
        except SchemaError as e:
            if name in reason and reason[name] not in str(e):
                raise SchemaError(f"planted {name}: refused for another reason: {e}") from None
            caught.append(name)
            continue
        raise SchemaError(f"planted {name}: not caught")
    return caught


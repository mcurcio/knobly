def read_json(name: str) -> dict:
    with (SCHEMA / name).open(encoding="utf-8") as f:
        return json.load(f)


def read_schema() -> Tuple[dict, dict, dict]:
    return read_json("api.json"), read_json("diagnostics.json"), read_json("protocol.json")


def planted(api: dict, diagnostics: dict, protocol: dict, languages: Sequence[Language]) -> List[str]:
    """Each check still bites: a broken copy of the schema must be refused (as tools/planted/ does for the grammar)."""

    def concept(a: dict, name: str) -> dict:
        return next(c for c in a["concepts"] if c["name"] == name)

    def member(a: dict, cname: str, mname: str) -> dict:
        return next(m for m in concept(a, cname)["members"] if m["name"] == mname)

    plants = {
        "variant missing": lambda a, d, p: concept(a, "variable")["variants"].remove("override variable"),
        "wrong kind": lambda a, d, p: concept(a, "set line").__setitem__("kind", "use"),
        "bad parent": lambda a, d, p: a["error groups"][1].__setitem__("parent", "no such group"),
        "unresolved type": lambda a, d, p: member(a, "document", "block").__setitem__("type", "writen block"),
        "type grammar": lambda a, d, p: member(a, "document", "block").__setitem__("type", "written block or"),
        "layer direction": lambda a, d, p: member(a, "document", "block").__setitem__("type", "rendered block"),
        "free text type": lambda a, d, p: member(a, "copy", "via").__setitem__("type", "the steps, innermost first"),
        "bug under the base": lambda a, d, p: next(g for g in a["error groups"] if g["name"] == "detached error").__setitem__("parent", "villanelle error"),
        "unknown trait": lambda a, d, p: member(a, "place", "people form").__setitem__("trait", "display"),
        "spelling collision": lambda a, d, p: a["concepts"].append({"name": "Statement kind".lower(), "layer": "written", "nature": "record", "members": []}),
        "bad found by": lambda a, d, p: d["codes"][0].__setitem__("found by", ["render"]),
        "protocol type": lambda a, d, p: p["shapes"][1]["fields"].__setitem__("path", "txt"),
        "generic arity": lambda a, d, p: member(a, "document", "block").__setitem__("type", "resolution of variable and text"),
        "arguments on a plain name": lambda a, d, p: member(a, "document", "block").__setitem__("type", "statement of text"),
        "generic without arguments": lambda a, d, p: member(a, "document", "block").__setitem__("type", "resolution"),
        "keyword in a name": lambda a, d, p: a["concepts"].append({"name": "left or right", "layer": "written", "nature": "record"}),
        "member spelling collision": lambda a, d, p: concept(a, "place")["members"].append(
            dict(member(a, "place", "resolved path"), name="resolved-path")),
        "member listed twice": lambda a, d, p: concept(a, "place")["members"].append(dict(member(a, "place", "resolved path"))),
        "kind value collision": lambda a, d, p: a["kinds"]["walk control"]["values"].extend(["zed x", "zed-x"]),
        "unportable regex": lambda a, d, p: a["patterns"]["variable name"].__setitem__("regex", "^\\w+$"),
        "lookahead regex": lambda a, d, p: a["patterns"]["variable name"].__setitem__("regex", "^(?=a)[a-z]+$"),
        "union after a function": lambda a, d, p: concept(a, "key rule").__setitem__("type", "function of directive to text or absent"),
        "generic in an argument list": lambda a, d, p: member(a, "document", "block").__setitem__(
            "type", "block of resolution of text and written directive"),
        "history in a protocol doc": lambda a, d, p: p["shapes"][0].__setitem__("doc", "a position (milestone 5)"),
        "bead id in a parameter doc": lambda a, d, p: next(f for f in a["free functions"] if f["name"] == "check lost updates")[
            "params"][-1].__setitem__("doc", "the texts (vil-umh.6)"),
        "template on a non-list": lambda a, d, p: next(g for g in a["error groups"] if g["name"] == "read error").__setitem__(
            "message", {"template": "{paths}"}) or next(g for g in a["error groups"] if g["name"] == "read error")["fields"][0].__setitem__("type", "text"),
        "bead id in a doc": lambda a, d, p: member(a, "document", "block").__setitem__("doc", "the top block (vil-umh.6)"),
        "history in a doc": lambda a, d, p: concept(a, "document").__setitem__("doc", "a file (milestone 5)"),
        "language in a doc": lambda a, d, p: d["codes"][0].__setitem__("meaning", f"a bad token, as {languages[0].name} reads it"),
        "undocumented member": lambda a, d, p: member(a, "document", "block").pop("doc"),
        "undocumented concept": lambda a, d, p: concept(a, "document").pop("doc"),
        "undocumented free function": lambda a, d, p: next(f for f in a["free functions"] if f["name"] == "parse").pop("doc"),
        "undocumented kind list": lambda a, d, p: a["kinds"]["node kind"].pop("doc"),
        "doc names an unlisted error": lambda a, d, p: member(a, "document graph", "save")["errors"].pop(),
    }
    # The refusal each newer plant must give, so it is caught by its own check and not by an earlier one by chance.
    reason = {
        "generic arity": "takes 1 type arguments, given 2",
        "arguments on a plain name": "takes 0 type arguments, given 1",
        "generic without arguments": "takes 1 type arguments, given 0",
        "keyword in a name": "type grammar's word 'or'",
        "member spelling collision": "both spell 'resolvedPath'",
        "member listed twice": "both spell 'resolved path'",
        "kind value collision": "both spell 'ZedX'",
        "unportable regex": "is no I-Regexp escape",
        "lookahead regex": "'(?'",
        "union after a function": "reads two ways",
        "generic in an argument list": "goes in parentheses",
        "history in a protocol doc": "names 'milestone 5'",
        "bead id in a parameter doc": "names 'vil-umh.6'",
        "a native type without a platform type": "has no platform type",
        "template on a non-list": "which is no list",
        "bead id in a doc": "names 'vil-umh.6'",
        "history in a doc": "names 'milestone 5'",
        "language in a doc": f"names {languages[0].name!r}",
        "spelling collision": "both spell",
        "undocumented member": "member 'block': has no doc",
        "undocumented concept": "concept 'document': has no doc",
        "undocumented free function": "free function 'parse': has no doc",
        "undocumented kind list": "kind list 'node kind': has no doc",
        "doc names an unlisted error": "its doc names the lost update error, which its errors do not list",
        "a root without a class": "must give it one of",
        "a language leaves out a used concept": "still uses",
        "an unknown module": "is not one of",
    }
    caught = []
    for name, plant in plants.items():
        broken = [json.loads(json.dumps(x)) for x in (api, diagnostics, protocol)]
        plant(*broken)
        try:
            Model(*broken, languages)
        except SchemaError as e:
            if name in reason and reason[name] not in str(e):
                raise SchemaError(f"planted {name}: refused for another reason: {e}") from None
            caught.append(name)
            continue
        raise SchemaError(f"planted {name}: not caught")
    # An emitter's own facts are checked as surely as the schema's: a broken copy of the first Language must be refused.
    first = languages[0]
    lang_plants = {
        "a root without a class": replace(first, error_roots={k: v for k, v in first.error_roots.items() if k != "misuse error"}),
        "a language leaves out a used concept": replace(first, omit=lambda name, nature: name == "source span"),
        "an unknown module": replace(first, modules={**first.modules, "network": "net"}),
    }
    # A Language that keeps a native type gives its platform type: plant on the first that has one.
    keeps_native = next((lang for lang in languages if lang.native), None)
    if keeps_native is not None:
        lang_plants["a native type without a platform type"] = replace(keeps_native, native={})
    for name, lang in lang_plants.items():
        try:
            Model(api, diagnostics, protocol, [lang if lang.key == other.key else other for other in languages])
        except SchemaError as e:
            if reason[name] not in str(e):
                raise SchemaError(f"planted {name}: refused for another reason: {e}") from None
            caught.append(name)
            continue
        raise SchemaError(f"planted {name}: not caught")
    return caught


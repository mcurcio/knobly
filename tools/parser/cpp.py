"""The generator's one language-specific step: writes the C++ lexer and parser header (frozen-m1.md section 3).

Output: cpp/include/villanelle/detail/syntax/parser.gen.hpp, never committed. Its interface (the token enum, the lexer
entry, the parser template and the hooks it calls) is frozen in frozen-m1.md section 3.2; the hand-written syntax layer
(cpp/include/villanelle/detail/syntax/parse.hpp) derives from the parser template and supplies the hooks.

Milestone 1 skeleton: writes the interface with stub bodies (no lexer table, every rule fails at once), so the hand
layer compiles against it. Lane P replaces the bodies with the lexer tables, the lookahead machines and one function
per rule.
"""

from __future__ import annotations

from typing import List

from g4 import Grammar

HEADER = "Generated by tools/parser/gen.py from grammar/Villanelle.g4; do not edit, and never commit."
RECOVER = ("document", "statements", "block")  # rules whose failure calls the hand-written recover_<rule>()


def render(grammar: Grammar) -> str:
    missing = [r for r in RECOVER if r not in grammar.rules]
    if missing:
        raise ValueError(f"recovery hooks for rules the grammar lacks: {', '.join(missing)}")
    out: List[str] = [
        f"// {HEADER}",
        "// PLACEHOLDER (milestone 1 skeleton): the interface only; every rule fails at once.",
        "#ifndef VILLANELLE_DETAIL_SYNTAX_PARSER_GEN_HPP",
        "#define VILLANELLE_DETAIL_SYNTAX_PARSER_GEN_HPP",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "#include <villanelle/kinds.hpp>",
        "#include <villanelle/support/config.hpp>",
        "",
        "VILLANELLE_NAMESPACE_BEGIN",
        "namespace syntax::detail {",
        "",
        "/// The lookahead kinds: every token kind in grammar order, then the end of the text.",
        f"enum class tk : std::uint8_t {{ {', '.join(grammar.tokens)}, end_of_text }};",
        f"inline constexpr std::size_t token_count = {len(grammar.tokens)};",
    ]
    for t in grammar.tokens:
        out.append(f"static_assert(static_cast<int>(tk::{t}) == static_cast<int>(::villanelle::token_kind::{t}));")
    out += [
        "",
        "/// One longest match: the token kind as an index into tk (-1: no token starts here) and its end in bytes.",
        "struct lex_match {",
        "    int kind;",
        "    std::size_t end;",
        "};",
        "",
        "/// The longest token starting at byte `at`. `decode(text, i, cp)` returns the byte length of the code point",
        "/// at `i` and stores it in `cp`, or 0 when the bytes there do not decode.",
        "template <class Decode>",
        "constexpr lex_match lex_longest(std::string_view text, std::size_t at, Decode decode) noexcept {",
        "    (void)text;",
        "    (void)decode;",
        "    return {-1, at};",
        "}",
        "",
        "/// One function per grammar rule. Derived supplies the hooks listed in frozen-m1.md section 3.2.",
        "template <class Derived>",
        "class generated_parser {",
        "protected:",
        "    std::size_t err_ = 0;  // where the last failed prediction died",
        "    Derived& self() noexcept { return static_cast<Derived&>(*this); }",
        "",
        "public:",
    ]
    for r in grammar.rules:
        call = f"self().recover_{r}()" if r in RECOVER else "false"
        out.append(f"    bool r_{r}() {{ return self().fail(self().pos()) || {call}; }}")
    out += ["};", "", "}  // namespace syntax::detail", "VILLANELLE_NAMESPACE_END", "",
            "#endif  // VILLANELLE_DETAIL_SYNTAX_PARSER_GEN_HPP", ""]
    return "\n".join(out)

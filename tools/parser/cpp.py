"""The generator's one language-specific step: writes the C++ lexer and parser header (frozen-m1.md section 3.2).

Output: cpp/include/knobly/detail/syntax/parser.gen.hpp, never committed. Its interface (the token enum, the lexer
entry, the parser template and the hooks it calls) is frozen in frozen-m1.md section 3.2; the hand-written syntax layer
(cpp/include/knobly/detail/syntax/parse.hpp) derives from the parser template and supplies the hooks.

The code is plain and deterministic; its layout is clang-format's (tools/parser/gen.py runs it). It needs neither
exceptions nor RTTI. Python 3.9+ standard library only.
"""

from __future__ import annotations

from typing import List, Tuple

from g4 import EOF, Grammar
from lexer import Dfa
from lookahead import Decision, Node, Plan

HEADER = "Generated by tools/parser/gen.py from grammar/Knobly.g4; do not edit, and never commit."
RECOVER = ("document", "statements", "block")  # rules whose failure calls the hand-written recover_<rule>()


def _tk(name: str) -> str:
    return "tk::end_of_text" if name == EOF else f"tk::{name}"


class _Rules:
    """One function per rule (r_<rule>, b_<rule>) and one per choice point (predict_<n>)."""

    def __init__(self, plan: Plan) -> None:
        self.plan = plan
        self.numbers = {id(d): n for n, d in enumerate(plan.decisions)}
        self.predicts: List[str] = []

    def predict(self, d: Decision) -> str:
        n = self.numbers[id(d)]
        where = f"{d.rule} (line {self.plan.grammar.lines[d.rule]})"
        if d.one_token:
            cases = {}
            for tok, s in d.edges[0].items():
                cases.setdefault(d.accept[s], []).append(tok)
            arms = [" ".join(f"case {_tk(t)}:" for t in toks) + f" return {a};" for a, toks in sorted(cases.items())]
            self.predicts += [
                f"// choice point {n}, in {where}: one token decides",
                f"int predict_{n}() noexcept {{",
                "switch (self().la(0)) {",
                *arms,
                "default: err_ = self().pos(); return -1;",
                "}",
                "}",
            ]
        else:
            self.predicts += [
                f"// choice point {n}, in {where}: {len(d.accept)} lookahead states",
                f"int predict_{n}() noexcept {{",
                "std::size_t i = 0;",
                "int s = 0;",
                "for (;;) {",
                "switch (s) {",
            ]
            for s, e in enumerate(d.edges):
                if d.accept[s] >= 0:
                    continue
                arms = [f"case {_tk(t)}: " + (f"return {d.accept[x]};" if d.accept[x] >= 0 else f"s = {x}; break;")
                        for t, x in e.items()]
                self.predicts += [f"case {s}:", "switch (self().la(i)) {", *arms,
                                  "default: err_ = self().pos() + i; return -1;", "}", "break;"]
            self.predicts += ["default: return -1;", "}", "++i;", "}", "}"]
        return f"predict_{n}()"

    def seq(self, nodes: tuple) -> List[str]:
        out: List[str] = []
        for node in nodes:
            out += self.node(node)
        return out

    def node(self, node: Node) -> List[str]:
        k = node[0]
        if k == "tok":
            return [f"if (!self().match({_tk(node[1])})) return false;"]
        if k == "rule":
            return [f"if (!r_{node[1]}()) return false;"]
        call = self.predict(node[2])
        a = f"a{self.numbers[id(node[2])]}"  # one name per choice point: no shadowing when they nest
        if k == "choice":
            out = [f"switch ({call}) {{"]
            for j, alt in enumerate(node[1]):
                out += [f"case {j}: {{", *self.seq(alt), "break;", "}"]
            return out + ["default: return self().fail(err_);", "}"]
        if k == "opt":
            return [f"if (int const {a} = {call}; {a} < 0) return self().fail(err_);", f"else if ({a} == 0) {{",
                    *self.seq(node[1]), "}"]
        if k == "star":
            return ["for (;;) {", f"int const {a} = {call};", f"if ({a} < 0) return self().fail(err_);",
                    f"if ({a} == 1) break;", *self.seq(node[1]), "}"]
        # plus: the body, then the decision to go round again
        return ["for (;;) {", *self.seq(node[1]), f"int const {a} = {call};",
                f"if ({a} < 0) return self().fail(err_);", f"if ({a} == 1) break;", "}"]

    def rule(self, name: str) -> Tuple[List[str], List[str]]:
        g = self.plan.grammar
        body = [f"bool b_{name}() {{", *self.seq(self.plan.rules[name]), "return true;", "}"]
        call = f"b_{name}() || self().recover_{name}()" if name in RECOVER else f"b_{name}()"
        kind = g.cst.get(name)
        if kind:
            head = [f"bool r_{name}() {{", f"self().open_node(::knobly::node_kind::{kind});",
                    f"if ({call}) {{", "self().close_node();", "return true;", "}", "self().fail_node();",
                    "return false;", "}"]
        else:
            head = [f"bool r_{name}() {{ return {call}; }}"]
        return [f"// {g.where(name)}" + (f", tree node {kind}" if kind else "")] + head, body


def render(plan: Plan, dfa: Dfa) -> str:
    g: Grammar = plan.grammar
    missing = [r for r in RECOVER if r not in g.rules]
    if missing:
        raise ValueError(f"recovery hooks for rules the grammar lacks: {', '.join(missing)}")
    flat, states = [], []
    for s, out in enumerate(dfa.trans):
        states.append((len(flat), len(out), dfa.accept[s]))
        flat += out
    if len(flat) > 0xFFFF or len(states) > 0xFFFF or len(dfa.tokens) > 127:
        raise ValueError("the lexer tables outgrow their 16-bit indexes")

    rules = _Rules(plan)
    heads: List[str] = []
    bodies: List[str] = []
    for r in g.rules:
        head, body = rules.rule(r)
        heads += head
        bodies += body

    out: List[str] = [
        f"// {HEADER}",
        f"// lexer: {len(dfa.tokens)} token kinds, {len(states)} states, {len(flat)} ranges; parser: {len(g.rules)} "
        f"rules, {plan.one_token} one-token choice points, {plan.longer} longer "
        f"({plan.longer_states} lookahead states)",
        "#ifndef KNOBLY_DETAIL_SYNTAX_PARSER_GEN_HPP",
        "#define KNOBLY_DETAIL_SYNTAX_PARSER_GEN_HPP",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "#include <knobly/kinds.hpp>",
        "#include <knobly/support/config.hpp>",
        "",
        "KNOBLY_NAMESPACE_BEGIN",
        "namespace syntax::detail {",
        "",
        "/// The lookahead kinds: every token kind in grammar order, then the end of the text.",
        f"enum class tk : std::uint8_t {{ {', '.join(dfa.tokens)}, end_of_text }};",
        f"inline constexpr std::size_t token_count = {len(dfa.tokens)};",
    ]
    out += [f"static_assert(static_cast<int>(tk::{t}) == static_cast<int>(::knobly::token_kind::{t}));"
            for t in dfa.tokens]
    out += [
        "",
        "/// One longest match: the token kind as an index into tk (-1: no token starts here) and its end in bytes.",
        "struct lex_match {",
        "int kind;",
        "std::size_t end;",
        "};",
        "",
        "/// The lexer DFA: each state's outgoing code-point ranges, sorted and disjoint, and the token it accepts.",
        "struct lex_range {",
        "char32_t lo;",
        "char32_t hi;",
        "std::uint16_t to;",
        "};",
        "inline constexpr lex_range lex_ranges[] = {",
        *(f"{{0x{lo:X}, 0x{hi:X}, {t}}}," for lo, hi, t in flat),
        "};",
        "struct lex_state {",
        "std::uint16_t first;",
        "std::uint16_t count;",
        "std::int8_t accept;",
        "};",
        "inline constexpr lex_state lex_states[] = {",
        *(f"{{{a}, {b}, {c}}}," for a, b, c in states),
        "};",
        "",
        "/// The longest token starting at byte `at`; ties go to the rule written first. `decode(text, i, cp)`",
        "/// returns the byte length of the code point at `i` and stores it in `cp`, or 0 when the bytes there do not",
        "/// decode (then the match stops).",
        "template <class Decode>",
        "constexpr lex_match lex_longest(std::string_view text, std::size_t at, Decode decode) noexcept {",
        "lex_match best{-1, at};",
        "std::size_t state = 0;",
        "std::size_t i = at;",
        "while (i < text.size()) {",
        "char32_t cp = 0;",
        "std::size_t const n = decode(text, i, cp);",
        "if (n == 0) break;",
        "lex_state const& here = lex_states[state];",
        "std::size_t next = sizeof(lex_states) / sizeof(lex_states[0]);",
        "for (std::size_t r = here.first, last = std::size_t{here.first} + here.count; r < last; ++r) {",
        "if (cp < lex_ranges[r].lo) break;",
        "if (cp <= lex_ranges[r].hi) {",
        "next = lex_ranges[r].to;",
        "break;",
        "}",
        "}",
        "if (next == sizeof(lex_states) / sizeof(lex_states[0])) break;",
        "state = next;",
        "i += n;",
        "if (lex_states[state].accept >= 0) best = lex_match{lex_states[state].accept, i};",
        "}",
        "return best;",
        "}",
        "",
        "/// One function per grammar rule. Derived supplies the hooks listed in frozen-m1.md section 3.2: la, pos,",
        f"/// match, fail, open_node, close_node, fail_node and recover_<rule> for {', '.join(RECOVER)}.",
        "template <class Derived>",
        "class generated_parser {",
        "protected:",
        "std::size_t err_ = 0;  // the token index where the last failed prediction died",
        "Derived& self() noexcept { return static_cast<Derived&>(*this); }",
        "",
        "public:",
        *heads,
        "",
        "protected:  // each rule's body without its node or recovery: a recovery hook resumes with b_<rule>()",
        *bodies,
        "",
        "private:",
        *rules.predicts,
        "};",
        "",
        "}  // namespace syntax::detail",
        "KNOBLY_NAMESPACE_END",
        "",
        "#endif  // KNOBLY_DETAIL_SYNTAX_PARSER_GEN_HPP",
        "",
    ]
    return "\n".join(out)

"""Mechanical translation of the syntax section of a REx/W3C EBNF grammar
(via `rex -xmlonly`) into plain BNF for Bison. No hand edits: EBNF operators
become fresh nonterminals with the textbook expansions."""
import sys, xml.etree.ElementTree as ET
NS = '{http://www.w3.org/2001/03/XPath/grammar}'
src = open(sys.argv[1], encoding='utf-8').read()
syntax_xml = src.split('<?TOKENS?>')[0] + '</g:grammar>'
root = ET.fromstring(syntax_xml)
prods = {p.get('name'): p for p in root.findall(NS + 'production')}
rules, tokens, lits, counter = {}, set(), {}, [0]

def fresh(base):
    counter[0] += 1
    return f'{base}_{counter[0]}'

def lit(s):
    if s not in lits:
        lits[s] = 'T_' + ''.join(c if c.isalnum() else f'x{ord(c):02X}' for c in s)
    return lits[s]

def seq(elems, owner):
    out = []
    for e in elems:
        out.extend(sym(e, owner))
    return out

def sym(e, owner):
    tag = e.tag[len(NS):]
    if tag == 'ref':
        n = e.get('name')
        if n not in prods:
            tokens.add('K_' + n)
            return ['K_' + n]
        return [n]
    if tag == 'string':
        return [lit(e.text)]
    if tag == 'sequence':
        return seq(list(e), owner)
    if tag == 'choice':
        n = fresh(owner + '_alt')
        rules[n] = [seq([c], owner) for c in e]
        return [n]
    if tag in ('optional', 'zeroOrMore', 'oneOrMore'):
        body = seq(list(e), owner)
        n = fresh(owner + '_' + tag)
        if tag == 'optional':
            rules[n] = [[], body]
        elif tag == 'zeroOrMore':
            rules[n] = [[], [n] + body]
        else:
            rules[n] = [body, [n] + body]
        return [n]
    raise SystemExit(f'unsupported construct {tag} in {owner}')

for name, p in prods.items():
    kids = list(p)
    if len(kids) == 1 and kids[0].tag == NS + 'choice':
        rules[name] = [seq([c], name) for c in kids[0]]
    else:
        rules[name] = [seq(kids, name)]

start = next(iter(prods))
print('/* generated by ebnf2bison.py from', sys.argv[1], '*/')
print('%token', ' '.join(sorted(tokens | set(lits.values()))))
print('%start', start)
print('%expect 0')
print('%%')
for n, alts in rules.items():
    print(n, ':', '\n  | '.join(' '.join(a) if a else '/* empty */' for a in alts), ';')
print('%%')
